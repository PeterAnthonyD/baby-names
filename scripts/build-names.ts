// Builds server/namesData.ts from the US Social Security baby name files.
//
// Download https://www.ssa.gov/oact/babynames/names.zip, unzip it, then run:
//   npm run build-names -- path/to/unzipped/folder
//
// The folder holds one yobYYYY.txt per year with lines like "Emma,F,19738".
// The SSA data is a US government work in the public domain.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const RECENT_YEARS = 20; // window used for popularity and sex split
const MIN_RECENT = 100; // babies in the recent window to make the deck
const MIN_PEAK = 500; // or babies in any single year (keeps classics)
const UNISEX_SHARE = 0.1; // each sex has at least 10% of babies

// Placeholders and words that hospitals sometimes report instead of a name.
const NOT_NAMES = new Set(
  ['Baby', 'Babyboy', 'Babygirl', 'Boy', 'Girl', 'Son', 'Daughter', 'Male', 'Female', 'Infant', 'Unknown',
    'Unnamed', 'Notnamed', 'Noname', 'Nameless', 'Twin', 'None'].map((n) => n.toLowerCase()),
);

// Drops placeholders, initials with no vowel (Jr, Md, Tj) and typos with a
// letter tripled (Willliam).
function isRealName(name: string) {
  return !NOT_NAMES.has(name.toLowerCase()) && /[aeiouy]/i.test(name) && !/(.)\1\1/i.test(name);
}

const dir = process.argv[2];
if (!dir) {
  console.error('Usage: npm run build-names -- path/to/ssa/folder');
  process.exit(1);
}

type Stat = { f: number; m: number; fRecent: number; mRecent: number; peak: number; byYear: Map<number, number> };
const stats = new Map<string, Stat>();

const files = readdirSync(dir).filter((f) => /^yob\d{4}\.txt$/.test(f));
const years = files.map((f) => Number(f.slice(3, 7))).sort((a, b) => a - b);
const lastYear = years[years.length - 1];
if (!lastYear) throw new Error(`No yobYYYY.txt files in ${dir}`);

for (const year of years) {
  const text = readFileSync(join(dir, `yob${year}.txt`), 'utf8');
  for (const line of text.split(/\r?\n/)) {
    if (!line) continue;
    const [name, sex, countText] = line.split(',');
    const n = Number(countText);
    let s = stats.get(name);
    if (!s) {
      s = { f: 0, m: 0, fRecent: 0, mRecent: 0, peak: 0, byYear: new Map() };
      stats.set(name, s);
    }
    const recent = year > lastYear - RECENT_YEARS;
    if (sex === 'F') {
      s.f += n;
      if (recent) s.fRecent += n;
    } else {
      s.m += n;
      if (recent) s.mRecent += n;
    }
    const yearTotal = (s.byYear.get(year) ?? 0) + n;
    s.byYear.set(year, yearTotal);
    s.peak = Math.max(s.peak, yearTotal);
  }
}

const sum = (s: Stat, from: number, to: number) => {
  let total = 0;
  for (let y = from; y <= to; y++) total += s.byYear.get(y) ?? 0;
  return total;
};

const kept = [...stats.entries()].filter(
  ([name, s]) => isRealName(name) && (s.fRecent + s.mRecent >= MIN_RECENT || s.peak >= MIN_PEAK),
);

// Rank within each sex for every year, like the SSA's own lists. A unisex
// name takes its better rank of the two each year.
const ranks = new Map<string, Map<number, number>>();
for (const year of years) {
  const bySex: Record<string, [string, number][]> = { F: [], M: [] };
  for (const line of readFileSync(join(dir, `yob${year}.txt`), 'utf8').split(/\r?\n/)) {
    const [name, sex, n] = line.split(',');
    if (name && bySex[sex]) bySex[sex].push([name, Number(n)]);
  }
  for (const list of Object.values(bySex)) {
    list.sort((a, b) => b[1] - a[1]);
    list.forEach(([name], i) => {
      let m = ranks.get(name);
      if (!m) ranks.set(name, (m = new Map()));
      m.set(year, Math.min(m.get(year) ?? Infinity, i + 1));
    });
  }
}

const TREND_YEARS = 5;
const rows = kept.map(([name, s]) => {
  const recent = s.fRecent + s.mRecent;
  const fShare = recent > 0 ? s.fRecent / recent : s.f / (s.f + s.m);
  const sex = fShare >= 1 - UNISEX_SHARE ? 'F' : fShare <= UNISEX_SHARE ? 'M' : 'U';
  const last5 = sum(s, lastYear - 4, lastYear);
  const prev5 = sum(s, lastYear - 9, lastYear - 5);
  const trend = last5 > prev5 * 1.25 ? 'up' : last5 < prev5 * 0.8 ? 'down' : 'flat';
  const byYear = ranks.get(name)!;
  // Best rank ever, and the first year it reached it.
  let peakRank = Infinity;
  let peakYear = 0;
  for (const [year, r] of [...byYear.entries()].sort((a, b) => a[0] - b[0])) {
    if (r < peakRank) [peakRank, peakYear] = [r, year];
  }
  const now = byYear.get(lastYear) ?? '';
  const before = byYear.get(lastYear - TREND_YEARS) ?? '';
  return [name, sex, now, recent, trend, peakYear, peakRank, before].join('\t');
});
rows.sort();

const out = `// Generated by scripts/build-names.ts from SSA data, ${years[0]}-${lastYear}. Do not edit.
// Columns: name, sex (F/M/U), rank in ${lastYear} within its sex, babies in the last ${RECENT_YEARS} years,
// trend (up/down/flat), year of best rank, best rank, rank in ${lastYear - TREND_YEARS}.
export const DATA_YEAR = ${lastYear};
export const TREND_YEARS = ${TREND_YEARS};
export const NAMES_TSV = ${JSON.stringify(rows.join('\n'))};
`;
writeFileSync(new URL('../server/namesData.ts', import.meta.url), out);
console.log(`Wrote ${rows.length} names (SSA ${years[0]}-${lastYear}) to server/namesData.ts`);
